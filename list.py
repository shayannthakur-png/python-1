# Create an empty list
empty_list = []
print(empty_list)

# Create a list of numbers
numbers = [1, 2, 3, 4, 5]
print(numbers)

# Use * operator to repeat list elements
triples = [1, 2, 3] * 3
print(triples)

# Reverse the given list
alist = [100, 200, 300, 400, 500]
alist = alist[::-1]
print(alist, "\n")